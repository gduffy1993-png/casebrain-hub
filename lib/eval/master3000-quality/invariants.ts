export function assertInvariantRegistry(registry: readonly InvariantDefinition[] = HISTORICAL_INVARIANTS): string[] {
  const issues: string[] = [];
  const ids = new Set<string>();
  for (const invariant of registry) {
    if (ids.has(invariant.id)) issues.push(`duplicate invariant id: ${invariant.id}`);
    ids.add(invariant.id);
    if (!invariant.oppositeDirectionRequired) {
      issues.push(`opposite-direction regression not required: ${invariant.id}`);
    }
    if (/caseId|defendantName|Arden|Patel|Monster/i.test(invariant.id)) {
      issues.push(`case-specific invariant id: ${invariant.id}`);
    }
  }
  return issues;
}

